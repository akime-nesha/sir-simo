    <h1>Paris</h1>
    <div class="image-container" style="text-align: center;">
        <img src="assets/img/paris1.jpg" alt="Eiffel Tower in Paris">
    </div>

    <p><span class="highlight">Paris</span>, the capital of France, is a major European city and a global hub for <strong>art, fashion, gastronomy, and culture</strong>. Known as the "City of Light," Paris has inspired countless artists, writers, and travelers throughout history.</p>

    <p>Its 19th-century cityscape is characterized by <strong>wide boulevards</strong>, historic architecture, and the <strong>River Seine</strong> flowing gracefully through the heart of the city. Iconic landmarks include the <strong>Eiffel Tower</strong>, <strong>Louvre Museum</strong>, <strong>Notre-Dame Cathedral</strong>, and the charming streets of <strong>Montmartre</strong>.</p>

    <div class="image-container" style="text-align: center;">
        <img src="assets/img/paris2.jpg" alt="Louvre Museum in Paris">
    </div>

    <h2>Cultural Highlights</h2>
    <p>Paris is famous for its world-class museums, galleries, and theaters. The <strong>Louvre</strong> houses the Mona Lisa, while the <strong>Musée d'Orsay</strong> features Impressionist masterpieces. Parisian fashion is globally renowned, with major fashion houses like <strong>Chanel</strong>, <strong>Louis Vuitton</strong>, and <strong>Dior</strong> headquartered here.</p>

    <div class="image-container" style="text-align: center;">
        <img src="assets/img/paris3.jpg" alt="Montmartre streets in Paris">
    </div>

    <h2>Fun Facts</h2>
    <div class="fun-fact">
        The Eiffel Tower was initially criticized by many Parisians but is now one of the most recognizable landmarks in the world.
    </div>
    <div class="fun-fact">
        Paris has more than 400 parks and gardens, including the famous <strong>Luxembourg Gardens</strong> and <strong>Tuileries Garden</strong>.
    </div>
    <div class="fun-fact">
        The city produces approximately 50 million baguettes every year, making it a true paradise for food lovers.
    </div>

    <h2>Transportation</h2>
    <p>Paris is well-connected with an extensive metro system, buses, trams, and bike-sharing services. Iconic yellow taxis and river cruises along the Seine offer unique ways to explore the city.</p>

