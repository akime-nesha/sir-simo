    <h1>Tokyo</h1>
    <div class="image-container" style="text-align: center;">
        <img src="assets/img/tokyo1.jpg" alt="Tokyo Skyline at Night">
    </div>

    <p><span class="highlight">Tokyo</span>, Japan’s bustling capital, is a city where the ultramodern meets the traditional. From neon-lit skyscrapers and cutting-edge technology to historic temples and serene gardens, Tokyo offers a unique blend of past and present.</p>

    <p>The city is home to iconic landmarks such as the <strong>Meiji Shinto Shrine</strong>, known for its towering torii gate and lush surrounding woods, the <strong>Tokyo Tower</strong>, and the futuristic <strong>Odaiba</strong> district. Tokyo is also famous for its culinary scene, offering everything from sushi and ramen to Michelin-starred restaurants.</p>

    <div class="image-container" style="text-align: center;">
        <img src="assets/img/tokyo2.jpg" alt="Meiji Shrine in Tokyo">
    </div>

    <h2>Cultural Highlights</h2>
    <p>Tokyo boasts world-class museums and entertainment districts. Visit the <strong>Museum of Emerging Science and Innovation (Miraikan)</strong>, explore the historic streets of <strong>Asakusa</strong> with the <strong>Senso-ji Temple</strong>, or experience the vibrant <strong>Shibuya Crossing</strong>, one of the busiest intersections in the world.</p>

    <div class="image-container" style="text-align: center;">
        <img src="assets/img/tokyo3.jpg" alt="Shibuya Crossing in Tokyo">
    </div>

    <h2>Fun Facts</h2>
    <div class="fun-fact">
        Tokyo is the largest metropolitan area in the world, with over 37 million people living in the Greater Tokyo Area.
    </div>
    <div class="fun-fact">
        The city has more Michelin-starred restaurants than any other city on Earth.
    </div>
    <div class="fun-fact">
        Tokyo’s public transportation system is one of the busiest and most punctual in the world, including its famous bullet trains (Shinkansen).
    </div>

    <h2>Transportation</h2>
    <p>Tokyo is incredibly well-connected via a vast network of trains, subways, buses, and ferries. The city's efficiency and punctuality make exploring even the busiest districts smooth and easy. Iconic sights such as the <strong>Tokyo Metro</strong> stations and the red-and-white Shinkansen trains are experiences in themselves.</p>

